// Precompiles the Pug templates into plain JS functions. The Cloudflare Worker
// can't compile Pug at runtime (Workers forbid eval/new Function), so both the
// static build and the Worker render from this generated module.
const pug = require('pug');
const { writeFileSync } = require('fs');

const templates = { index: './src/index.pug', embed: './src/embed.pug' };

const source = Object.entries(templates)
  .map(([name, file]) => {
    const fn = pug.compileFileClient(file, { name, compileDebug: false });
    return `exports.${name} = (function () {\n${fn}\nreturn ${name};\n})();\n`;
  })
  .join('\n');

writeFileSync('./src/templates.generated.js', `// Generated by scripts/compile-templates.js. Do not edit.\n${source}`);
console.log('Compiled templates to src/templates.generated.js');
